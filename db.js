/* ============================================================
   PICKLJAY — shared data layer for all pages.
   Wraps Firebase Authentication and Firestore behind one small
   object, window.PJ, so the pages themselves contain no Firebase
   code. Do not edit this file; put your settings in
   firebase-config.js instead.
   ============================================================ */
(function () {
  "use strict";

  var CFG = window.PJ_CONFIG || {};
  var PJ = {
    configured: false,
    failure: null,
    _app: null, _auth: null, _dbf: null,
    _user: null, _cbs: []
  };

  function looksUnset(v) {
    return !v || String(v).indexOf("PASTE") === 0;
  }
  PJ.needsSetup = function () {
    var f = CFG.firebase || {};
    return looksUnset(f.apiKey) || looksUnset(f.projectId) || looksUnset(f.appId);
  };

  try {
    if (typeof firebase === "undefined") {
      PJ.failure = "The Firebase library did not load. Check your connection and reload.";
    } else if (PJ.needsSetup()) {
      PJ.failure = "setup";
    } else {
      PJ._app  = firebase.initializeApp(CFG.firebase);
      PJ._auth = firebase.auth();
      PJ._dbf  = firebase.firestore();
      try { PJ._auth.setPersistence(firebase.auth.Auth.Persistence.LOCAL); } catch (e) {}
      PJ.configured = true;
    }
  } catch (e) {
    PJ.failure = (e && e.message) || String(e);
  }

  /* ---------- who is signed in ---------- */
  function shape(u) {
    if (!u) return null;
    var email = (u.email || "").toLowerCase();
    return {
      uid: u.uid,
      email: u.email,
      role: email === String(CFG.adminEmail || "").toLowerCase() ? "admin" : "general"
    };
  }
  PJ.currentUser = function () { return PJ._user; };
  PJ.role = function () { return PJ._user ? PJ._user.role : null; };
  PJ.isAdmin = function () { return PJ.role() === "admin"; };

  /* Fires once the first auth check has finished, then on every change. */
  PJ.onAuth = function (cb) {
    PJ._cbs.push(cb);
    if (!PJ.configured) { setTimeout(function () { cb(null); }, 0); return; }
    if (PJ._authStarted) { if (PJ._settled) cb(PJ._user); return; }
    PJ._authStarted = true;
    PJ._auth.onAuthStateChanged(function (u) {
      PJ._user = shape(u);
      PJ._settled = true;
      PJ._cbs.forEach(function (f) { try { f(PJ._user); } catch (e) {} });
    });
  };

  PJ.signIn = function (email, password) {
    if (!PJ.configured) return Promise.reject(new Error(PJ.failure || "not configured"));
    return PJ._auth.signInWithEmailAndPassword(email, password)
      .then(function (c) { PJ._user = shape(c.user); return PJ._user; });
  };
  PJ.signOut = function () {
    if (!PJ.configured) return Promise.resolve();
    return PJ._auth.signOut().then(function () { PJ._user = null; });
  };

  /* Turns Firebase's error codes into something a student can act on. */
  PJ.explain = function (err) {
    var c = (err && (err.code || err.message)) || "";
    if (/wrong-password|invalid-credential|invalid-login/.test(c))
      return "That password is not right.";
    if (/user-not-found/.test(c))
      return "That account does not exist yet. Check with your teacher.";
    if (/too-many-requests/.test(c))
      return "Too many tries. Wait a minute and try again.";
    if (/network|unavailable|offline/i.test(c))
      return "No connection to the server. Check your signal and try again.";
    if (/operation-not-allowed/.test(c))
      return "Email sign-in is not switched on in the Firebase console yet.";
    if (/permission-denied/.test(c))
      return "You are not allowed to do that with this account.";
    return (err && err.message) || "Something went wrong.";
  };

  /* ---------- the tournament ---------- */
  function tdoc(slug) { return PJ._dbf.collection("tournaments").doc(slug); }
  function adoc(slug) { return PJ._dbf.collection("adminState").doc(slug); }

  PJ.getTournament = function (slug) {
    return tdoc(slug).get().then(function (d) { return d.exists ? d.data() : null; });
  };
  /* Live: cb runs immediately and again on every change. */
  PJ.watchTournament = function (slug, cb, onErr) {
    return tdoc(slug).onSnapshot(
      function (d) { cb(d.exists ? d.data() : null); },
      function (e) { if (onErr) onErr(e); });
  };
  PJ.saveTournament = function (slug, payload, course) {
    return tdoc(slug).set({
      payload: payload,
      course: course || null,
      updatedAt: firebase.firestore.FieldValue.serverTimestamp()
    }, { merge: true });
  };
  PJ.saveAdminState = function (slug, json) {
    return adoc(slug).set({
      state: json,
      updatedAt: firebase.firestore.FieldValue.serverTimestamp()
    });
  };
  PJ.getAdminState = function (slug) {
    return adoc(slug).get().then(function (d) {
      return d.exists ? (d.data().state || null) : null;
    });
  };

  /* ---------- results sent in by scoring teams ---------- */
  function rid(slug, gameIdx) { return slug + "__" + gameIdx; }

  PJ.postResult = function (slug, gameIdx, teamIdx, sa, sb) {
    var u = PJ.currentUser();
    if (!u) return Promise.reject(new Error("not signed in"));
    return PJ._dbf.collection("results").doc(rid(slug, gameIdx)).set({
      slug: slug, gameIdx: gameIdx, teamIdx: teamIdx,
      sa: sa, sb: sb, by: u.uid,
      updatedAt: firebase.firestore.FieldValue.serverTimestamp()
    });
  };
  PJ.watchResults = function (slug, cb, onErr) {
    return PJ._dbf.collection("results").where("slug", "==", slug)
      .onSnapshot(function (snap) {
        var out = [];
        snap.forEach(function (d) { out.push(d.data()); });
        out.sort(function (a, b) { return (a.gameIdx || 0) - (b.gameIdx || 0); });
        cb(out);
      }, function (e) { if (onErr) onErr(e); });
  };
  PJ.clearResults = function (slug, gameIdxs) {
    var batch = PJ._dbf.batch();
    (gameIdxs || []).forEach(function (g) {
      batch.delete(PJ._dbf.collection("results").doc(rid(slug, g)));
    });
    return batch.commit();
  };

  /* ---------- page guard ---------- */
  /* Sends anyone without the right role back to the sign-in page. */
  PJ.require = function (role, onReady) {
    PJ.onAuth(function (u) {
      if (!u) { location.replace("index.html" + (location.hash || "")); return; }
      if (role === "admin" && u.role !== "admin") { location.replace("board.html"); return; }
      onReady(u);
    });
  };

  window.PJ = PJ;
})();
